export const filterDemoCouriers = (
  items: CourierConnection[],
  filters: CourierFilterState
): CourierConnection[] => {
  return items.filter((item) => {
    if (filters.status !== 'all' && item.status !== filters.status) {
      return false;
    }
    if (filters.searchQuery.trim()) {
      const q = filters.searchQuery.toLowerCase();
      const matchName = item.courierName.toLowerCase().includes(q);
      const matchAcc = (item.accountId || '').toLowerCase().includes(q);
      if (!matchName && !matchAcc) return false;
    }
    if (filters.serviceType !== 'all' && !item.enabledServices.includes(filters.serviceType as any)) {
      return false;
    }
    return true;
  });
};

export const getCourierConnectionDetail = async (courierId: string): Promise<CourierConnection | null> => {
  const match = DEMO_COURIER_CONNECTIONS.find((c) => c.courierId === courierId || c.id === courierId);
  return Promise.resolve(match || DEMO_COURIER_CONNECTIONS[0]);
};
